// Run against a debug WebView with an isolated MOVINIGHT_QA_DATA_DIR.
const { chromium } = require(process.env.MOVINIGHT_PLAYWRIGHT_PATH || 'playwright');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
assert(process.env.MOVINIGHT_QA_DATA_DIR, 'Use an isolated QA library');
let browser;
(async () => {
  browser = await chromium.connectOverCDP(process.env.MOVINIGHT_QA_CDP || 'http://127.0.0.1:9230');
  const page = browser.contexts().flatMap(c => c.pages()).find(p => p.url().includes('tauri.localhost'));
  assert(page, 'Real Tauri WebView is running');
  const errors = []; page.on('pageerror', e => errors.push(e.message));
  const invoke = (command, args = {}) => page.evaluate(({ command, args }) => window.__TAURI__.core.invoke(command, args), { command, args });
  const passed = message => console.log('PASS', message);
  await page.reload();
  await page.waitForSelector('#main-app.show');
  await page.waitForSelector('#results-grid .result-card');
  assert.equal(await page.locator('[data-type="all"].toggle-btn').getAttribute('aria-pressed'), 'true');
  const types = await page.locator('#results-grid .result-card').evaluateAll(cards => [...new Set(cards.map(c => c.dataset.type))]);
  assert.deepEqual(types.sort(), ['movie','tv']);
  await page.locator('#view-more-btn').click();
  await page.waitForFunction(() => document.querySelectorAll('#results-grid .result-card').length > 40);
  const keys = await page.locator('#results-grid .result-card').evaluateAll(cards => cards.map(c => `${c.dataset.type}:${c.dataset.id}`));
  assert.equal(new Set(keys).size, keys.length);
  passed('Discovery All renders and paginates both formats with distinct identities');
  const status = await invoke('start_mcp');
  let rpcId = 0;
  const rpc = async (method, params = {}) => {
    const response = await fetch(status.url, { method:'POST', headers:{ 'Content-Type':'application/json', 'Accept':'application/json, text/event-stream', 'Authorization':`Bearer ${status.token}` }, body:JSON.stringify({ jsonrpc:'2.0', id:++rpcId, method, params }) });
    assert.equal(response.status, 200); return response.json();
  };
  const call = async (name, args = {}) => {
    const reply = await rpc('tools/call', { name, arguments:args });
    assert.equal(reply.result.isError, false, JSON.stringify(reply));
    return JSON.parse(reply.result.content[0].text);
  };
  const init = await rpc('initialize', { protocolVersion:'2025-11-25' });
  assert.match(init.result.instructions, /Suggestions tab/); assert.match(init.result.instructions, /limit=1000/);
  const list = await rpc('tools/list');
  assert.equal(list.result.tools.length, 12);
  assert(!list.result.tools.some(t => /approve|remove|delete/.test(t.name)));
  const options = await call('get_discovery_options');
  assert(options.movie.genres.length && options.tv.genres.length && options.languages.length);
  assert(options.movie.providers.every(p => !('logo_path' in p)));
  passed('Actual MCP handshake teaches large research and routes picks to Suggestions; filter menus are available');
  const first = await call('discover_titles', { content_type:'all', limit:37, year_from:2010, year_to:2020, with_original_language:'en', min_rating:7, hide_incomplete:true });
  assert.equal(first.returned, 37); assert(first.next_cursor);
  const next = await call('absorb_next_titles', { cursor:first.next_cursor, limit:43 });
  assert.equal(next.returned, 43);
  const identities = first.titles.concat(next.titles).map(t => `${t.content_type}:${t.id}`);
  assert.equal(new Set(identities).size, 80);
  assert(first.titles.concat(next.titles).every(t => !('poster_path' in t) && !('backdrop_path' in t) && !('youtube_url' in t) && t.overview && t.vote_average >= 7 && t.original_language === 'en'));
  passed('Live filtered absorption resumes a partial mixed page and excludes visual payloads');
  let bulk = await call('discover_titles', { content_type:'all', limit:1000 });
  let absorbed = 0; const bulkKeys = new Set(); const batchCounts = [];
  for (let batch = 0; batch < 4; batch++) {
    assert(bulk.returned > 0 && bulk.returned <= 1000);
    batchCounts.push(bulk.returned); absorbed += bulk.returned;
    for (const title of bulk.titles) bulkKeys.add(`${title.content_type}:${title.id}`);
    if (absorbed >= 2000) break;
    assert(bulk.next_cursor);
    bulk = await call('absorb_next_titles', { cursor:bulk.next_cursor, limit:Math.min(1000,2000-absorbed) });
  }
  assert.equal(absorbed, 2000); assert.equal(bulkKeys.size, 2000);
  passed(`Live TMDB bulk research absorbed 2,000 distinct titles in batches of ${batchCounts.join(', ')}`);
  const library = await call('get_library');
  const watched = library.watched.find(w => w.content_type === 'tv'); assert(watched);
  const watchedPath = path.join(process.env.MOVINIGHT_QA_DATA_DIR,'watched.json');
  const historyBefore = fs.readFileSync(watchedPath,'utf8');
  const details = await call('get_title_details', { id:watched.id, content_type:'tv' });
  assert(!('poster_path' in details)); assert(details.seasons.every(s => !('poster_path' in s)));
  const remaining = details.seasons.filter(s => s.season_number > 0 && s.air_date && s.air_date <= '2026-10-07' && !watched.watched_seasons.includes(s.season_number)).map(s => s.season_number);
  assert(remaining.length);
  const season = await call('publish_suggestion', { id:watched.id, content_type:'tv', source:'discovery', reason:'Continue the next aired season while keeping saved progress.', recommended_seasons:[remaining[0]] });
  const duplicate = await call('publish_suggestion', { id:watched.id, content_type:'tv', source:'discovery', reason:'Continue the next aired season; your checked seasons are preserved.', recommended_seasons:[remaining[0]] });
  assert.equal(duplicate.suggestion_id, season.suggestion_id);
  await page.locator('#picks-nav').click();
  await page.waitForSelector(`#suggestion-list [data-suggestion="${season.suggestion_id}"]`);
  await page.locator(`#suggestion-list [data-suggestion="${season.suggestion_id}"][data-suggestion-review="approve"]`).click();
  await page.waitForFunction(id => document.querySelector(`#suggestion-list [data-suggestion-id="${id}"] .suggestion-label`)?.textContent.includes('APPROVED'), season.suggestion_id);
  let after = await call('get_library');
  assert(!after.waitlist.some(w => w.id === watched.id && w.content_type === 'tv'));
  assert.equal(fs.readFileSync(watchedPath,'utf8'), historyBefore);
  await page.locator('#watched-nav').click();
  await page.waitForSelector('#watched-season-suggestions:not([hidden]) .suggestion');
  passed('Watched TV approval preserves exact history and shows aired-season recommendations in Watched');
  const fresh = first.titles.find(t => !library.watched.concat(library.waitlist).some(i => i.id === t.id && i.content_type === t.content_type)); assert(fresh);
  const suggestion = await call('publish_suggestion', { id:fresh.id, content_type:fresh.content_type, source:'discovery', reason:'A researched fit from the selected years, language and rating range.' });
  assert(!('poster_path' in suggestion.item));
  assert(!(await call('get_library')).waitlist.some(i => i.id === fresh.id && i.content_type === fresh.content_type));
  await page.locator('#picks-nav').click();
  await page.waitForSelector(`#suggestion-list [data-suggestion="${suggestion.suggestion_id}"]`);
  await page.locator(`#suggestion-list [data-suggestion="${suggestion.suggestion_id}"][data-suggestion-review="approve"]`).click();
  await page.waitForFunction(id => document.querySelector(`#suggestion-list [data-suggestion-id="${id}"] .suggestion-label`)?.textContent.includes('APPROVED'), suggestion.suggestion_id);
  after = await call('get_library'); assert.equal(after.waitlist.filter(i => i.id === fresh.id && i.content_type === fresh.content_type).length, 1);
  passed('Discovery recommendations arrive in Suggestions without research input and add new titles only on approval');
  const research = await invoke('save_research', { text:watched.title, instructions:'Verify this watched title without moving it to Waitlist.' });
  const proposal = await call('propose_waitlist', { id:watched.id, content_type:'tv', research_id:research.id, requested_title:watched.title, reason:'The canonical show matches the supplied title.' });
  await invoke('get_ai_workspace'); await page.locator('#refresh-ai').click();
  await page.locator('#suggestions-proposal-review').evaluate(el => el.open = true);
  await page.locator(`#suggestions-proposal-list [data-proposal="${proposal.proposal.proposal_id}"][data-review="approve"]`).click();
  await page.waitForFunction(() => document.querySelector('#suggestions-proposal-count').textContent === '0');
  assert.equal(fs.readFileSync(watchedPath,'utf8'), historyBefore);
  assert(!(await call('get_library')).waitlist.some(i => i.id === watched.id && i.content_type === 'tv'));
  assert((await call('get_suggestions')).some(s => s.source === 'research' && s.status === 'approved'));
  passed('Pasted watched-title matches are reviewable in Suggestions and preserve watched state');
  const rejectCandidate = next.titles.find(t => t.id !== fresh.id || t.content_type !== fresh.content_type);
  const rejected = await call('publish_suggestion', { id:rejectCandidate.id,content_type:rejectCandidate.content_type,source:'discovery',reason:'A candidate to review.' });
  await page.locator('#refresh-ai').click();
  await page.locator(`#suggestion-list [data-suggestion="${rejected.suggestion_id}"][data-suggestion-review="reject"]`).click();
  await page.waitForFunction(id => !document.querySelector(`#suggestion-list [data-suggestion-id="${id}"]`), rejected.suggestion_id);
  const returned = await call('publish_suggestion', { id:rejectCandidate.id,content_type:rejectCandidate.content_type,source:'discovery',reason:'A fresh request can recommend this title again.' });
  assert.notEqual(returned.suggestion_id,rejected.suggestion_id);
  passed('Rejecting a suggestion allows it to return for a later request');
  await page.locator('#watched-nav').click();
  await page.locator('#watched-season-suggestion-list .result-card').first().click();
  await page.waitForSelector(`label[for="season-cb-${remaining[0]}"]`);
  await page.locator(`label[for="season-cb-${remaining[0]}"]`).click();
  assert(await page.locator(`.season-checkbox[data-season="${remaining[0]}"]`).isChecked());
  await page.locator('#season-tracker-save').click();
  await page.waitForFunction(() => document.querySelector('#watched-season-suggestions').hidden);
  const progress = (await call('get_library')).watched.find(w => w.id === watched.id && w.content_type === 'tv');
  assert.equal(progress.watched_date, watched.watched_date); assert(progress.watched_seasons.includes(remaining[0]));
  assert((await call('get_suggestions')).some(s => s.suggestion_id === season.suggestion_id && s.status === 'approved'));
  if (await page.locator('#close-movie-details').isVisible()) await page.locator('#close-movie-details').click();
  await page.locator('#picks-nav').click();
  passed('Checking off a recommended season removes it from the catch-up section while preserving approved history');
  await page.screenshot({ path:'.qa-output/discovery-suggestions.png' });
  const cdp = await browser.contexts()[0].newCDPSession(page);
  await cdp.send('Emulation.setDeviceMetricsOverride', { width:390,height:844,deviceScaleFactor:1,mobile:false });
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
  assert(await page.locator('.header-nav .nav-btn').evaluateAll(buttons => buttons.every(button => {
    const range = document.createRange(); range.selectNodeContents(button);
    const text = range.getBoundingClientRect(); const bounds = button.getBoundingClientRect();
    return text.left >= bounds.left && text.right <= bounds.right;
  })), 'All navigation labels fit their buttons');
  await page.screenshot({ path:'.qa-output/discovery-suggestions-mobile.png' });
  await cdp.send('Emulation.clearDeviceMetricsOverride');
  await page.reload(); await page.waitForSelector('#main-app.show'); await page.locator('#picks-nav').click();
  await page.waitForSelector('#suggestion-list .suggestion');
  assert((await call('get_suggestions')).filter(s => s.status === 'approved').length >= 3);
  assert.deepEqual(errors, []);
  passed('Suggestions persist after reload and fit mobile width without JavaScript errors');
  await invoke('stop_mcp'); await browser.close();
})().catch(async error => { console.error(error.stack); await browser?.close(); process.exitCode=1; });
